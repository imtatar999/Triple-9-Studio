"""Writes docs/HOW-TO-USE.md from the program's own Help > How To Use text (studio_help.py), so the GitHub page and
the window always say the same. The GitHub page also shows the screenshots: a line like
    [[image: fix.png | caption]]
in studio_help.PAGES becomes a picture from docs/images (the program's Help window skips those lines).
Run:  python MAINTENANCE/make_docs.py"""
import re
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(root / "SYNCED-LYRICS-DOWNLOADER-MAIN"))
import studio_help as help_text  # noqa: E402


def markdown(text):
    out = []
    for line in text.splitlines():
        line = re.sub(r'\*\*"([^"]+)"\*\*', r"**\1**", line)  # **"Button"** -> **Button**
        picture = re.match(r"\[\[image:\s*([^|\]]+?)\s*\|\s*(.*?)\s*\]\]$", line)
        if picture:
            line = f"![{picture.group(2)}](images/{picture.group(1)})\n\n*{picture.group(2)}*\n"
        out.append(line)
    return "\n".join(out)


def anchor(title):
    return re.sub(r"[^a-z0-9 -]", "", title.lower()).replace(" ", "-")


parts = ["<!-- Generated by MAINTENANCE/make_docs.py from the program's help text; edit studio_help.py, not this file. -->\n",
         "# Triple 9 Studio - how to use\n",
         "The same guide is inside the program (**Help > How To Use**), there without the pictures. "
         "Back to the [main page](../README.md).\n"]
toc, body = [], []
for page, content in help_text.PAGES.items():
    heading = content.splitlines()[0][2:]
    toc.append(f"- [{heading}](#{anchor(heading)})")
    body.append("\n---\n")
    body.append(markdown(content))
parts.append("\n".join(toc))
parts.extend(body)
(root / "docs" / "HOW-TO-USE.md").write_text("\n".join(parts) + "\n", encoding="utf-8")
print("docs/HOW-TO-USE.md written")
